let current = 'fa';

function getI18n(lang) {
  if (lang && STRINGS[lang]) current = lang;
  return STRINGS[current];
}

function t(key, subs) {
  let s = (STRINGS[current] && STRINGS[current][key]) || STRINGS.fa[key] || key;
  if (subs) {
    for (const k of Object.keys(subs)) s = s.replace('{' + k + '}', subs[k]);
  }
  return s;
}

module.exports = { getI18n, t, setLang: (l) => { if (STRINGS[l]) current = l; }, lang: () => current };
